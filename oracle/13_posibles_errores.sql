-- ============================================================
-- ElectriSys — Tabla de posibles errores de escritura del asistente NLP
-- 13. DDL de posibles_errores
-- Ejecutar conectado como ELECTRISYS, después de 02_ddl_tablas.sql.
--
-- Cada fila es una forma mal escrita conocida de una marca, un modelo o
-- una categoría ("jilus" -> "Hilux"). El NER del microservicio la consulta
-- antes de comparar por similitud, porque RapidFuzz no reconoce los errores
-- que cambian o intercambian letras (fuzz.ratio("jilus", "hilux") = 60).
--
-- La mantiene el agente de nlp-service (app/ner/agente_errores.py): al
-- crearse una marca o un modelo de vehículo genera sus errores y los
-- inserta con MERGE. 14_seed_posibles_errores.sql carga la tabla del
-- catálogo semilla.
--
-- Columnas:
--   tipo      qué entidad es: marca | modelo | categoria
--   error     la forma mal escrita, YA NORMALIZADA (minúsculas, sin tildes,
--             sin puntuación: "cx 5", no "CX-5")
--   correcto  el nombre oficial tal como está en el catálogo ("Baterías")
--   nivel     1 una letra · 2 fonético/apodo/sigla · 3 dos errores realistas
--             · 4 reservado (errores arbitrarios; en general NO se guardan,
--             los cubre el respaldo por similitud del extractor)
--   origen    auto (lo generó el generador) | manual (escrito a mano)
--   nota      tipo de error ("letra repetida", "fonético", "apodo"...)
--
-- Sin FK hacia el catálogo a propósito: marca y modelo no son tablas, son
-- columnas de VEHICULOS, y "correcto" apunta a VEHICULOS.marca,
-- VEHICULOS.modelo o CATEGORIAS.nombre según "tipo" — una FK no puede
-- elegir destino por el valor de otra columna. La integridad la garantiza
-- el agente (solo registra nombres que vienen del catálogo). Ver
-- oracle/docs/normalizacion.md.
-- ============================================================

CREATE TABLE posibles_errores (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    tipo           VARCHAR2(10)  NOT NULL,
    error          VARCHAR2(120) NOT NULL,
    correcto       VARCHAR2(120) NOT NULL,
    nivel          NUMBER(1)     NOT NULL,
    origen         VARCHAR2(10)  DEFAULT 'auto' NOT NULL,
    nota           VARCHAR2(60),
    creado_en      TIMESTAMP DEFAULT SYSTIMESTAMP,
    actualizado_en TIMESTAMP,
    -- Un error apunta a UN solo nombre por tipo (si dos nombres comparten un
    -- error es una colisión y el generador lo descarta). Este índice único
    -- es también el camino de acceso de la consulta del NER:
    --   SELECT correcto FROM posibles_errores WHERE tipo = :t AND error = :e
    CONSTRAINT uq_posibles_errores      UNIQUE (tipo, error),
    CONSTRAINT ck_posibles_errores_tipo CHECK (tipo IN ('marca', 'modelo', 'categoria')),
    CONSTRAINT ck_posibles_errores_nivel CHECK (nivel BETWEEN 1 AND 4),
    CONSTRAINT ck_posibles_errores_origen CHECK (origen IN ('manual', 'auto'))
);

-- "Todos los errores de Hilux": borrar o regenerar los de un nombre.
CREATE INDEX idx_posibles_errores_correcto ON posibles_errores(tipo, correcto);

