SET DEFINE OFF;

-- Cada fila: una forma errónea (error) y el nombre correcto al que apunta.
-- tipo: marca | modelo | categoria.  nivel: 1 a 3 (el 4 se resuelve por
-- similitud con RapidFuzz y no se guarda).  origen: auto (agente) | manual.
CREATE TABLE posibles_errores (
    id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    tipo      VARCHAR2(10)  NOT NULL,
    error     VARCHAR2(100) NOT NULL,
    correcto  VARCHAR2(100) NOT NULL,
    nivel     NUMBER(1)     NOT NULL,
    origen    VARCHAR2(10)  DEFAULT 'auto' NOT NULL,
    nota      VARCHAR2(100),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT ck_pe_tipo   CHECK (tipo IN ('marca', 'modelo', 'categoria')),
    CONSTRAINT ck_pe_nivel  CHECK (nivel BETWEEN 1 AND 4),
    CONSTRAINT ck_pe_origen CHECK (origen IN ('auto', 'manual')),
    CONSTRAINT uq_pe_error_correcto UNIQUE (tipo, error, correcto)
);

-- Búsqueda del asistente: WHERE tipo = :t AND error = :texto
CREATE INDEX idx_pe_tipo_error ON posibles_errores(tipo, error);
CREATE INDEX idx_pe_correcto   ON posibles_errores(tipo, correcto);

-- Errores descartados por coincidir con una palabra común del español
-- (control de falsos positivos).
CREATE TABLE posibles_errores_avisos (
    id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    tipo      VARCHAR2(10)  NOT NULL,
    error     VARCHAR2(100) NOT NULL,
    correcto  VARCHAR2(100) NOT NULL,
    nivel     NUMBER(1)     NOT NULL,
    motivo    VARCHAR2(100) NOT NULL,
    CONSTRAINT ck_pea_tipo CHECK (tipo IN ('marca', 'modelo', 'categoria'))
);

-- Resumen por tipo y nivel
CREATE OR REPLACE VIEW v_posibles_errores_resumen AS
SELECT tipo, nivel, origen, COUNT(*) AS total
  FROM posibles_errores
 GROUP BY tipo, nivel, origen;

