-- ElectriSys — Migración a Oracle 23ai
-- 10. Pedidos a proveedor (órdenes de reabastecimiento)
-- Ejecutar conectado como el usuario ELECTRISYS.
--
-- Un "pedido" acá es una ORDEN DE COMPRA hacia un proveedor, no un
-- encargo de un cliente: por eso apunta a PROVEEDORES y no a CLIENTES,
-- y por eso el stock SUBE al recibirlo en vez de bajar al crearlo.
-- Decisión de negocio confirmada con el equipo antes de programar
-- (la interpretación alterna —encargo de cliente— habría llevado a
-- reservar stock al crear el pedido, que NO es lo que se implementó).
--
-- Ciclo de vida:
--   solicitado ──▶ en_transito ──▶ recibido   (suma stock, estado final)
--        └──────────────┴────────▶ cancelado  (no toca stock, estado final)
--
-- Mismo mapeo de tipos MySQL -> Oracle documentado en 02_ddl_tablas.sql.
-- ============================================================

-- ── Secuencia para el consecutivo del número de pedido ────────────
-- CREATE SEQUENCE no soporta "OR REPLACE"/"IF NOT EXISTS" — se envuelve
-- en un bloque anónimo para que el script sea re-ejecutable, igual que
-- seq_numero_venta en 06_packages_plsql.sql.
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_sequences WHERE sequence_name = 'SEQ_NUMERO_PEDIDO';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE seq_numero_pedido START WITH 1 INCREMENT BY 1';
    END IF;
END;
/

-- ── Pedidos (cabecera) ────────────────────────────────────────────
CREATE TABLE pedidos (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    numero         VARCHAR2(20) NOT NULL,
    proveedor_id   NUMBER NOT NULL,
    usuario_id     NUMBER NOT NULL,          -- quién hizo la orden de compra
    estado         VARCHAR2(20) DEFAULT 'solicitado' NOT NULL,
    subtotal       NUMBER(14,2) DEFAULT 0 NOT NULL,
    total          NUMBER(14,2) DEFAULT 0 NOT NULL,
    fecha_esperada DATE,                     -- fecha estimada de llegada
    notas          VARCHAR2(4000),
    creado_en      TIMESTAMP DEFAULT SYSTIMESTAMP,
    updated_at     TIMESTAMP,
    recibido_en    TIMESTAMP,                -- se llena solo al pasar a 'recibido'
    CONSTRAINT uq_pedidos_numero    UNIQUE (numero),
    CONSTRAINT fk_pedidos_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores(id),
    CONSTRAINT fk_pedidos_usuario   FOREIGN KEY (usuario_id)   REFERENCES usuarios(id),
    CONSTRAINT ck_pedidos_estado    CHECK (estado IN ('solicitado','en_transito','recibido','cancelado')),
    CONSTRAINT ck_pedidos_total     CHECK (total >= 0 AND subtotal >= 0)
);

-- ── Detalle del pedido ────────────────────────────────────────────
-- precio_unit es el precio de COMPRA acordado con el proveedor, no el
-- precio_venta del repuesto (por eso no se copia de repuestos.precio_venta).
CREATE TABLE pedido_detalle (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    pedido_id   NUMBER NOT NULL,
    repuesto_id NUMBER NOT NULL,
    cantidad    NUMBER(10) DEFAULT 1 NOT NULL,
    precio_unit NUMBER(12,2) NOT NULL,
    subtotal    NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_peddet_pedido   FOREIGN KEY (pedido_id)   REFERENCES pedidos(id) ON DELETE CASCADE,
    CONSTRAINT fk_peddet_repuesto FOREIGN KEY (repuesto_id) REFERENCES repuestos(id),
    CONSTRAINT ck_peddet_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_peddet_precio   CHECK (precio_unit >= 0)
);

-- ── Índices ───────────────────────────────────────────────────────
CREATE INDEX idx_pedidos_estado     ON pedidos(estado);
CREATE INDEX idx_pedidos_proveedor  ON pedidos(proveedor_id);
CREATE INDEX idx_pedidos_fecha      ON pedidos(creado_en);
CREATE INDEX idx_peddet_pedido      ON pedido_detalle(pedido_id);

-- ── Trigger BEFORE INSERT: consecutivo del número ────────────────
-- El número se arma en la base y no en PHP para que sea único aunque
-- dos usuarios creen un pedido en el mismo milisegundo (la secuencia es
-- atómica; un uniqid() de PHP no garantiza el consecutivo legible).
CREATE OR REPLACE TRIGGER trg_pedidos_numero
    BEFORE INSERT ON pedidos
    FOR EACH ROW
    WHEN (NEW.numero IS NULL)
BEGIN
    :NEW.numero := 'PED-' || LPAD(seq_numero_pedido.NEXTVAL, 6, '0');
END;
/

-- ── Trigger BEFORE UPDATE: updated_at + estados finales ──────────
-- Agrupa las tres reglas en un solo trigger por la misma razón que
-- trg_ventas_before_update (updated_at + version): Oracle no garantiza
-- el orden entre varios triggers BEFORE UPDATE sobre la misma tabla.
--
-- 'recibido' y 'cancelado' son estados FINALES: salir de 'recibido'
-- dejaría el stock sumado sin pedido que lo respalde, y "descancelar"
-- un pedido saltaría el flujo de aprobación. La regla vive en la base
-- —no solo en PHP— porque el stock es el activo que se está protegiendo.
CREATE OR REPLACE TRIGGER trg_pedidos_before_update
    BEFORE UPDATE ON pedidos
    FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;

    IF :OLD.estado = 'recibido' AND :NEW.estado != 'recibido' THEN
        RAISE_APPLICATION_ERROR(-20010,
            'Un pedido ya recibido no puede cambiar de estado (el stock ya fue sumado al inventario).');
    END IF;

    IF :OLD.estado = 'cancelado' AND :NEW.estado != 'cancelado' THEN
        RAISE_APPLICATION_ERROR(-20011,
            'Un pedido cancelado no puede reabrirse; crea un pedido nuevo.');
    END IF;

    IF :NEW.estado = 'recibido' AND :OLD.estado != 'recibido' THEN
        :NEW.recibido_en := SYSTIMESTAMP;
    END IF;
END;
/

-- ── Trigger AFTER UPDATE: suma de stock al recibir ───────────────
-- Espejo de trg_ventas_anulada_restaura_stock: la entrada de mercancía
-- al inventario es una regla de negocio de la base de datos, no de la
-- aplicación — un pedido marcado 'recibido' desde SQL Developer también
-- debe sumar el stock. PedidoModel NUNCA toca repuestos.stock, para no
-- sumarlo dos veces (mismo contrato que VentaModel con las ventas).
CREATE OR REPLACE TRIGGER trg_pedidos_recibido_suma_stock
    AFTER UPDATE OF estado ON pedidos
    FOR EACH ROW
    WHEN (NEW.estado = 'recibido' AND OLD.estado != 'recibido')
DECLARE
    CURSOR c_detalle IS
        SELECT repuesto_id, cantidad
          FROM pedido_detalle
         WHERE pedido_id = :OLD.id;
BEGIN
    FOR fila IN c_detalle LOOP
        UPDATE repuestos
           SET stock = stock + fila.cantidad
         WHERE id = fila.repuesto_id;
    END LOOP;
END;
/

-- ── Privilegios por rol ───────────────────────────────────────────
-- Coherente con la decisión de producto: el módulo de pedidos es de
-- ADMIN y DUEÑO. El vendedor no recibe ningún privilegio sobre estas
-- tablas — ni SELECT — porque reabastecer no es parte de su operación
-- (ver el mismo criterio aplicado a AUDIT_LOG en 08_roles_privilegios.sql).
--
-- El DUEÑO sí recibe INSERT/UPDATE acá, a diferencia del resto del esquema
-- donde es solo lectura: autorizar una compra y darla por recibida es una
-- decisión gerencial, no administrativa. No recibe DELETE porque un pedido
-- se cancela cambiando su estado, nunca se borra.
GRANT SELECT, INSERT, UPDATE, DELETE ON pedidos         TO rol_electrisys_admin;
GRANT SELECT, INSERT, UPDATE, DELETE ON pedido_detalle  TO rol_electrisys_admin;
GRANT SELECT, INSERT, UPDATE ON pedidos        TO rol_electrisys_dueno;
GRANT SELECT, INSERT, UPDATE ON pedido_detalle TO rol_electrisys_dueno;

