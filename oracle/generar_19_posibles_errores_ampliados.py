"""Genera oracle/19_posibles_errores_ampliados.sql a partir de los CSV del NLP.

La semilla original (14_seed_posibles_errores.sql) cargó 58.833 errores y 112 avisos.
Desde entonces el CSV creció (nlp-service/data/errores/); este script escribe un
SQL con SOLO las filas que la semilla no trae, de forma que Oracle y el archivo
vuelvan a coincidir sin borrar ni modificar nada.

Esquema posterior a la fase 2 de 3FN: la tabla ya no guarda el texto `correcto`
sino `marca_id` / `modelo_id` / `categoria_id`. El destino se resuelve por nombre
contra los catálogos; lo que no está en el catálogo (o un modelo ambiguo entre
marcas) se omite, igual que hizo la migración.

Uso (desde la raíz del repo):
    python oracle/generar_19_posibles_errores_ampliados.py
"""
import csv
import re
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
SEMILLA = RAIZ / "oracle" / "14_seed_posibles_errores.sql"
CSV_ERRORES = RAIZ / "nlp-service" / "data" / "errores" / "posibles_errores.csv"
CSV_AVISOS = RAIZ / "nlp-service" / "data" / "errores" / "posibles_errores_avisos.csv"
SALIDA = RAIZ / "oracle" / "19_posibles_errores_ampliados.sql"
LOTE = 200  # filas por INSERT: mantiene cada sentencia corta para SQL*Plus

# VALUES (id,'tipo','error','correcto',nivel,'origen','nota')  — con '' como comilla escapada
_TXT = r"'((?:[^']|'')*)'"
RE_ERROR = re.compile(r"INTO posibles_errores \(id,tipo,error,correcto,nivel,origen,nota\) VALUES \(\d+," + _TXT + "," + _TXT + "," + _TXT + r",(\d)," + _TXT)
RE_AVISO = re.compile(r"INTO posibles_errores_avisos \(id,tipo,error,correcto,nivel,motivo\) VALUES \(\d+," + _TXT + "," + _TXT + "," + _TXT + r",(\d)," + _TXT)

# Resuelve el destino por nombre; descarta lo que no está en el catálogo.
RESOLVER = "\n".join([
    "LEFT JOIN marcas m ON s.tipo = 'marca' AND m.nombre = s.correcto",
    "LEFT JOIN categorias c ON s.tipo = 'categoria' AND c.nombre = s.correcto",
    "LEFT JOIN modelos mo ON s.tipo = 'modelo' AND mo.nombre = s.correcto",
    "  AND (SELECT COUNT(*) FROM modelos x WHERE x.nombre = s.correcto) = 1",
    "WHERE (m.id IS NOT NULL OR mo.id IS NOT NULL OR c.id IS NOT NULL)",
])


def q(valor: str) -> str:
    return "'" + valor.replace("'", "''") + "'"


def main() -> None:
    semilla = SEMILLA.read_text(encoding="utf-8")
    ya_errores = {(t.replace("''", "'"), e.replace("''", "'"), c.replace("''", "'"))
                  for t, e, c, _n, _o in RE_ERROR.findall(semilla)}
    ya_avisos = {(t.replace("''", "'"), e.replace("''", "'"), c.replace("''", "'"))
                 for t, e, c, _n, _m in RE_AVISO.findall(semilla)}

    with CSV_ERRORES.open(encoding="utf-8", newline="") as f:
        nuevos = [r for r in csv.DictReader(f) if (r["tipo"], r["error"], r["correcto"]) not in ya_errores]
    with CSV_AVISOS.open(encoding="utf-8", newline="") as f:
        avisos = [r for r in csv.DictReader(f) if (r["tipo"], r["error"], r["correcto"]) not in ya_avisos]

    out = [
        "-- ============================================================",
        "-- ElectriSys — Ampliación de posibles_errores y posibles_errores_avisos",
        f"-- Candidatos: {len(nuevos)} errores de escritura y {len(avisos)} avisos que la semilla",
        "-- 14_seed_posibles_errores.sql no trae (están en nlp-service/data/errores/).",
        "--",
        "-- Ejecutar como ELECTRISYS, después de 16_normalizacion_3fn_fase2.sql.",
        "-- UTF-8: usar NLS_LANG=.AL32UTF8 al correr sqlplus.",
        "--",
        "-- Esquema 3FN fase 2: el destino se resuelve por nombre contra marcas/modelos/",
        "-- categorias; lo que no está en el catálogo se omite (igual que en la migración).",
        "--",
        "-- Idempotente: los errores usan IGNORE_ROW_ON_DUPKEY_INDEX sobre la clave única",
        "-- (tipo, error, destino) y los avisos llevan NOT EXISTS, así que puede correrse",
        "-- varias veces sin duplicar ni tocar lo que ya existe.",
        "-- Generado por oracle/generar_19_posibles_errores_ampliados.py",
        "-- ============================================================",
        "SET DEFINE OFF;",
        "SET SQLBLANKLINES ON;",
        "",
        "-- La semilla insertó ids explícitos: el contador automático debe seguir después del máximo.",
        "ALTER TABLE posibles_errores MODIFY id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE);",
        "ALTER TABLE posibles_errores_avisos MODIFY id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE);",
        "",
    ]
    for i in range(0, len(nuevos), LOTE):
        selects = [
            f"SELECT {q(r['tipo'])} AS tipo,{q(r['error'])} AS error,{q(r['correcto'])} AS correcto,"
            f"{int(r['nivel'])} AS nivel,{q(r['origen'])} AS origen,{q(r['nota']) if r['nota'] else 'NULL'} AS nota FROM dual"
            for r in nuevos[i:i + LOTE]
        ]
        out.append("INSERT /*+ IGNORE_ROW_ON_DUPKEY_INDEX(posibles_errores(tipo,error,marca_id,modelo_id,categoria_id)) */")
        out.append("INTO posibles_errores (tipo,error,marca_id,modelo_id,categoria_id,nivel,origen,nota)")
        out.append("SELECT s.tipo, s.error, m.id, mo.id, c.id, s.nivel, s.origen, s.nota FROM (")
        out.append("\nUNION ALL\n".join(selects) + ") s")
        out.append(RESOLVER + ";")
        out.append("COMMIT;")
        out.append("")
    for r in avisos:
        out.append("\n".join([
            "INSERT INTO posibles_errores_avisos (tipo,error,marca_id,modelo_id,categoria_id,nivel,motivo)",
            "SELECT s.tipo, s.error, m.id, mo.id, c.id, s.nivel, s.motivo FROM (SELECT "
            f"{q(r['tipo'])} AS tipo,{q(r['error'])} AS error,{q(r['correcto'])} AS correcto,"
            f"{int(r['nivel'])} AS nivel,{q(r['motivo'])} AS motivo FROM dual) s",
            RESOLVER,
            "AND NOT EXISTS (SELECT 1 FROM posibles_errores_avisos x WHERE x.tipo = s.tipo AND x.error = s.error",
            "  AND NVL(x.marca_id,0) = NVL(m.id,0) AND NVL(x.modelo_id,0) = NVL(mo.id,0)"
            " AND NVL(x.categoria_id,0) = NVL(c.id,0));",
        ]))
    out += ["COMMIT;", "", "PROMPT Posibles errores y avisos ampliados.", ""]
    SALIDA.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"errores candidatos: {len(nuevos)} | avisos candidatos: {len(avisos)} | semilla: {len(ya_errores)} errores, {len(ya_avisos)} avisos")


if __name__ == "__main__":
    main()
