-- QUÉ ARREGLA
--  * VEHICULOS repetía la marca en cada modelo (modelo -> marca es una
--    dependencia transitiva, rompe la 3FN). Se separa en MARCAS y MODELOS
--    y VEHICULOS pasa a apuntar a un modelo (modelo_id).
--  * La respuesta del asistente no tenía dónde guardarse de forma atómica
--    (1FN): se crean CONSULTA_ENTIDADES y CONSULTA_RECOMENDACIONES.
--
-- POR QUÉ ES "FASE 1"
--  Esta fase es compatible hacia atrás: vehiculos.marca y vehiculos.modelo
--  SE CONSERVAN y un trigger completa modelo_id cuando se inserta con texto.
--  La FASE 2 (16_normalizacion_3fn_fase2.sql) quita esas columnas y las
--  derivadas de las cabeceras; usa vw_vehiculos y vw_totales_documento.
--
-- ROLES: este script NO otorga privilegios a roles (los roles se crean en
-- 08_roles_privilegios.sql, que corre después). Los GRANT de las tablas y
-- vistas nuevas están en 08.
--
-- RE-EJECUTABLE: cada paso comprueba si ya existe. Si la fase 2 ya se
-- aplicó (vehiculos sin marca/modelo) los pasos de la fase 1 se omiten.
-- ============================================================
SET SERVEROUTPUT ON
SET DEFINE OFF

-- ── 1. Tablas MARCAS y MODELOS ───────────────────────────────────
DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM user_tables WHERE table_name = 'MARCAS';
    IF v = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE marcas (
                id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                nombre    VARCHAR2(80) NOT NULL,
                creado_en TIMESTAMP DEFAULT SYSTIMESTAMP,
                CONSTRAINT uq_marcas_nombre UNIQUE (nombre)
            )';
        DBMS_OUTPUT.PUT_LINE('Tabla MARCAS creada.');
    END IF;

    SELECT COUNT(*) INTO v FROM user_tables WHERE table_name = 'MODELOS';
    IF v = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE modelos (
                id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                marca_id  NUMBER NOT NULL,
                nombre    VARCHAR2(80) NOT NULL,
                creado_en TIMESTAMP DEFAULT SYSTIMESTAMP,
                CONSTRAINT fk_modelos_marca FOREIGN KEY (marca_id) REFERENCES marcas(id),
                CONSTRAINT uq_modelos_marca_nombre UNIQUE (marca_id, nombre)
            )';
        DBMS_OUTPUT.PUT_LINE('Tabla MODELOS creada.');
    END IF;
END;
/

-- ── 2. Cargar marcas y modelos desde los vehículos existentes ─────
-- Dinámico y condicionado a que vehiculos.marca exista: así el script sigue
-- siendo válido (y no hace nada) si la fase 2 ya quitó esas columnas.
DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM user_tab_columns
     WHERE table_name = 'VEHICULOS' AND column_name = 'MARCA';
    IF v > 0 THEN
        EXECUTE IMMEDIATE '
            INSERT INTO marcas (nombre)
            SELECT DISTINCT TRIM(v.marca) FROM vehiculos v
             WHERE v.marca IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM marcas m WHERE m.nombre = TRIM(v.marca))';
        EXECUTE IMMEDIATE '
            INSERT INTO modelos (marca_id, nombre)
            SELECT DISTINCT m.id, TRIM(v.modelo)
              FROM vehiculos v
              JOIN marcas m ON m.nombre = TRIM(v.marca)
             WHERE v.modelo IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM modelos mo
                                WHERE mo.marca_id = m.id AND mo.nombre = TRIM(v.modelo))';
        COMMIT;
    END IF;
END;
/

-- ── 3. VEHICULOS apunta a MODELOS ────────────────────────────────
DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM user_tab_columns
     WHERE table_name = 'VEHICULOS' AND column_name = 'MODELO_ID';
    IF v = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE vehiculos ADD (modelo_id NUMBER)';
        DBMS_OUTPUT.PUT_LINE('Columna VEHICULOS.MODELO_ID agregada.');
    END IF;

    SELECT COUNT(*) INTO v FROM user_tab_columns
     WHERE table_name = 'VEHICULOS' AND column_name = 'MARCA';
    IF v > 0 THEN
        EXECUTE IMMEDIATE '
            UPDATE vehiculos v
               SET modelo_id = (SELECT mo.id
                                  FROM modelos mo
                                  JOIN marcas m ON m.id = mo.marca_id
                                 WHERE m.nombre = TRIM(v.marca) AND mo.nombre = TRIM(v.modelo))
             WHERE v.modelo_id IS NULL';
        COMMIT;
    END IF;
END;
/

DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM user_constraints WHERE constraint_name = 'FK_VEHICULOS_MODELO';
    IF v = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE vehiculos ADD CONSTRAINT fk_vehiculos_modelo
                           FOREIGN KEY (modelo_id) REFERENCES modelos(id)';
    END IF;
    SELECT COUNT(*) INTO v FROM user_indexes WHERE index_name = 'IDX_VEHICULOS_MODELO';
    IF v = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX idx_vehiculos_modelo ON vehiculos(modelo_id)';
    END IF;
END;
/

-- ── 4. Trigger de compatibilidad con el backend actual ───────────
-- Si alguien inserta o edita un vehículo con marca/modelo en texto (como
-- hace VehiculoModel hoy) y no trae modelo_id, se busca o se crea la marca
-- y el modelo y se completa modelo_id. Así las dos formas conviven.
-- Se crea solo mientras vehiculos tenga la columna marca (la fase 2 la quita
-- junto con este trigger).
DECLARE
    v NUMBER;
BEGIN
    SELECT COUNT(*) INTO v FROM user_tab_columns
     WHERE table_name = 'VEHICULOS' AND column_name = 'MARCA';
    IF v > 0 THEN
        EXECUTE IMMEDIATE q'[
CREATE OR REPLACE TRIGGER trg_vehiculos_modelo_id
    BEFORE INSERT OR UPDATE OF marca, modelo ON vehiculos
    FOR EACH ROW
DECLARE
    v_marca_id  marcas.id%TYPE;
    v_modelo_id modelos.id%TYPE;
BEGIN
    -- Hay que resolver el modelo si: no trae modelo_id, o cambió el texto de
    -- marca/modelo sin cambiar modelo_id (sería quedarse con uno desactualizado).
    IF :NEW.marca IS NOT NULL AND :NEW.modelo IS NOT NULL AND
       ( :NEW.modelo_id IS NULL
         OR (UPDATING AND :NEW.modelo_id = :OLD.modelo_id
             AND (:NEW.marca <> :OLD.marca OR :NEW.modelo <> :OLD.modelo)) ) THEN
        BEGIN
            SELECT id INTO v_marca_id FROM marcas WHERE nombre = TRIM(:NEW.marca);
        EXCEPTION WHEN NO_DATA_FOUND THEN
            INSERT INTO marcas (nombre) VALUES (TRIM(:NEW.marca)) RETURNING id INTO v_marca_id;
        END;
        BEGIN
            SELECT id INTO v_modelo_id FROM modelos
             WHERE marca_id = v_marca_id AND nombre = TRIM(:NEW.modelo);
        EXCEPTION WHEN NO_DATA_FOUND THEN
            INSERT INTO modelos (marca_id, nombre) VALUES (v_marca_id, TRIM(:NEW.modelo))
            RETURNING id INTO v_modelo_id;
        END;
        :NEW.modelo_id := v_modelo_id;
    END IF;
END;]';
    END IF;
END;
/

-- Vista con la forma 3FN: marca y modelo salen de los joins, no de columnas repetidas.
CREATE OR REPLACE VIEW vw_vehiculos AS
SELECT v.id, m.nombre AS marca, mo.nombre AS modelo,
       v.anio_desde, v.anio_hasta, v.motor, v.combustible
  FROM vehiculos v
  JOIN modelos mo ON mo.id = v.modelo_id
  JOIN marcas  m  ON m.id  = mo.marca_id;

